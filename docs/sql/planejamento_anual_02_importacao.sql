-- ─── Normalização (mesma regra do Manus: trim, minúsculas, espaços únicos, sem acento)
create extension if not exists unaccent with schema extensions;

create or replace function public.cda_pa_normalizar(t text) returns text
language sql immutable as $$
  select lower(regexp_replace(trim(extensions.unaccent('extensions.unaccent'::regdictionary, coalesce(t,''))), '\s+', ' ', 'g'));
$$;

-- ─── Apelidos de importação (antes fixos no código do Manus) ────────────────
create table public.cda_pa_alias_importacao (
  id              bigint generated by default as identity primary key,
  alias           text not null,
  alias_norm      text generated always as (public.cda_pa_normalizar(alias)) stored unique,
  centro_custo_id bigint not null references public.cda_pa_centro_custo(id) on delete cascade,
  criado_em       timestamptz not null default now(),
  atualizado_em   timestamptz not null default now(),
  atualizado_por  text
);
create trigger touch before update on public.cda_pa_alias_importacao for each row execute function public.cda_pa_touch();
alter table public.cda_pa_alias_importacao enable row level security;
create policy leitura  on public.cda_pa_alias_importacao for select to authenticated using (public.cda_pa_pode_ler());
create policy inclusao on public.cda_pa_alias_importacao for insert to authenticated with check (public.cda_pa_pode_escrever());
create policy edicao   on public.cda_pa_alias_importacao for update to authenticated using (public.cda_pa_pode_escrever()) with check (public.cda_pa_pode_escrever());
create policy exclusao on public.cda_pa_alias_importacao for delete to authenticated using (public.cda_pa_pode_escrever());

