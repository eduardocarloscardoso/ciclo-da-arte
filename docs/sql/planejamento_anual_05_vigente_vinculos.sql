-- Valor vigente por centro de custo, com histórico (vale a linha mais recente
-- cujo início é <= ao mês de referência).
--   tipo 'valor'      → R$ por mês (despesas fixas/financeiras; receitas recorrentes)
--   tipo 'percentual' → % sobre a receita vinculada (despesas variáveis)
create table if not exists public.cda_pa_valor_vigente (
  id              bigint generated by default as identity primary key,
  centro_custo_id bigint  not null references public.cda_pa_centro_custo(id),
  ano_inicio      integer not null,
  mes_inicio      integer not null check (mes_inicio between 1 and 12),
  tipo            text    not null check (tipo in ('valor','percentual')),
  valor           numeric(15,2) not null,
  motivo          text,
  criado_por      text,
  criado_em       timestamptz not null default now(),
  unique (centro_custo_id, ano_inicio, mes_inicio)
);
create index if not exists cda_pa_valor_vigente_cc on public.cda_pa_valor_vigente (centro_custo_id, ano_inicio, mes_inicio);

-- Vínculo despesa variável → canal de receita (subconta de RECEITAS).
-- Padrão na subconta de despesa; exceção no centro de custo (se o centro tiver
-- vínculos próprios, eles substituem os da subconta). Sem vínculo = todos os
-- canais. pct_rateio null = rateio automático pela receita de cada canal.
create table if not exists public.cda_pa_vinculo (
  id                   bigint generated by default as identity primary key,
  despesa_subconta_id  bigint references public.cda_pa_subconta(id),
  despesa_centro_id    bigint references public.cda_pa_centro_custo(id),
  receita_subconta_id  bigint not null references public.cda_pa_subconta(id),
  pct_rateio           numeric(6,2) check (pct_rateio is null or (pct_rateio > 0 and pct_rateio <= 100)),
  criado_por           text,
  criado_em            timestamptz not null default now(),
  check ((despesa_subconta_id is null) <> (despesa_centro_id is null))
);
create unique index if not exists cda_pa_vinculo_sub_uk on public.cda_pa_vinculo (despesa_subconta_id, receita_subconta_id) where despesa_subconta_id is not null;
create unique index if not exists cda_pa_vinculo_cc_uk  on public.cda_pa_vinculo (despesa_centro_id,  receita_subconta_id) where despesa_centro_id  is not null;

do $$
declare t text;
begin
  foreach t in array array['cda_pa_valor_vigente','cda_pa_vinculo'] loop
    execute format('alter table public.%I enable row level security', t);
    begin
      execute format('create policy leitura  on public.%I for select to authenticated using (public.cda_pa_pode_ler())', t);
      execute format('create policy inclusao on public.%I for insert to authenticated with check (public.cda_pa_pode_escrever())', t);
      execute format('create policy edicao   on public.%I for update to authenticated using (public.cda_pa_pode_escrever()) with check (public.cda_pa_pode_escrever())', t);
      execute format('create policy exclusao on public.%I for delete to authenticated using (public.cda_pa_pode_escrever())', t);
    exception when duplicate_object then null; end;
  end loop;
end $$;

