insert into public.cda_pa_vinculo (despesa_subconta_id, despesa_centro_id, receita_subconta_id, criado_por)
select case when v.desp_cc is null then ds.id end,
       case when v.desp_cc is not null then dc.id end,
       rs.id, 'migração 05'
  from v
  join public.cda_pa_subconta ds on ds.nome = v.desp_sub
  join public.cda_pa_conta dct on dct.id = ds.conta_id and dct.tipo = 'DESPESAS'
  left join public.cda_pa_centro_custo dc on dc.subconta_id = ds.id and dc.nome = v.desp_cc
  join public.cda_pa_subconta rs on rs.nome = v.rec_sub
  join public.cda_pa_conta rct on rct.id = rs.conta_id and rct.tipo = 'RECEITAS'
 where (v.desp_cc is null or dc.id is not null)
   and not exists (select 1 from public.cda_pa_vinculo x
                    where x.receita_subconta_id = rs.id
                      and ((v.desp_cc is null and x.despesa_subconta_id = ds.id) or (v.desp_cc is not null and x.despesa_centro_id = dc.id)));

-- Produção Varejo → todos os canais de varejo (todos menos Private Label e Market Place)
insert into public.cda_pa_vinculo (despesa_subconta_id, receita_subconta_id, criado_por)
select ds.id, rs.id, 'migração 05'
  from public.cda_pa_subconta ds join public.cda_pa_conta dct on dct.id = ds.conta_id and dct.tipo = 'DESPESAS'
  cross join public.cda_pa_subconta rs join public.cda_pa_conta rct on rct.id = rs.conta_id and rct.tipo = 'RECEITAS'
 where ds.nome = 'Produção Varejo' and rs.ativo and rs.nome not in ('PRIVATE LABEL','Market Place - Vendas Terceiros')
   and not exists (select 1 from public.cda_pa_vinculo x where x.despesa_subconta_id = ds.id and x.receita_subconta_id = rs.id);
