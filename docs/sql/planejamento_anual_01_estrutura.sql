-- ─── Função de permissão (padrão cda_orc_*, slug 'planejamento_anual') ─────
create or replace function public.cda_pa_pode_ler() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from equipe e
    where lower(e.email) = lower(auth.jwt() ->> 'email')
      and (e.is_admin or 'planejamento_anual' = any(e.projetos)));
$$;

create or replace function public.cda_pa_pode_escrever() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from equipe e
    where lower(e.email) = lower(auth.jwt() ->> 'email')
      and (e.is_admin or 'planejamento_anual' = any(e.projetos))
      and coalesce(e.permissao, 'leitura_escrita') = 'leitura_escrita');
$$;

create or replace function public.cda_pa_is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from equipe e
    where lower(e.email) = lower(auth.jwt() ->> 'email') and e.is_admin);
$$;

-- ─── Carimbo de atualização ──────────────────────────────────────────────────
create or replace function public.cda_pa_touch() returns trigger
language plpgsql as $$
begin
  new.atualizado_em := now();
  new.atualizado_por := coalesce(auth.jwt() ->> 'email', new.atualizado_por);
  return new;
end $$;

-- ─── Nível 1: Conta ─────────────────────────────────────────────────────────
create table public.cda_pa_conta (
  id             bigint generated by default as identity primary key,
  nome           text not null,
  tipo           text not null check (tipo in ('RECEITAS','DESPESAS')),
  ordem          int  not null default 0,
  ativo          boolean not null default true,
  criado_em      timestamptz not null default now(),
  atualizado_em  timestamptz not null default now(),
  atualizado_por text
);

-- ─── Nível 2: Subconta ──────────────────────────────────────────────────────
create table public.cda_pa_subconta (
  id             bigint generated by default as identity primary key,
  conta_id       bigint not null references public.cda_pa_conta(id) on delete restrict,
  nome           text not null,
  ordem          int  not null default 0,
  ativo          boolean not null default true,
  criado_em      timestamptz not null default now(),
  atualizado_em  timestamptz not null default now(),
  atualizado_por text,
  unique (conta_id, nome)
);

-- ─── Nível 3: Centro de Custo ───────────────────────────────────────────────
-- A conta é derivada da subconta (sem redundância, diferente do Manus).
create table public.cda_pa_centro_custo (
  id             bigint generated by default as identity primary key,
  subconta_id    bigint not null references public.cda_pa_subconta(id) on delete restrict,
  nome           text not null,
  ordem          int  not null default 0,
  ativo          boolean not null default true,
  criado_em      timestamptz not null default now(),
  atualizado_em  timestamptz not null default now(),
  atualizado_por text,
  unique (subconta_id, nome)
);

-- ─── Previsto anual por centro ──────────────────────────────────────────────
create table public.cda_pa_orcamento_previsto (
  id             bigint generated by default as identity primary key,
  ano            int not null check (ano between 2020 and 2100),
  centro_custo_id bigint not null references public.cda_pa_centro_custo(id) on delete restrict,
  valor_previsto numeric(15,2) not null default 0,
  criado_em      timestamptz not null default now(),
  atualizado_em  timestamptz not null default now(),
  atualizado_por text,
  unique (ano, centro_custo_id)
);

-- ─── Realizado mensal (somente meses 1–12; provisão tem tabela própria) ─────
create table public.cda_pa_realizado_mensal (
  id             bigint generated by default as identity primary key,
  ano            int not null check (ano between 2020 and 2100),
  mes            int not null check (mes between 1 and 12),
  centro_custo_id bigint not null references public.cda_pa_centro_custo(id) on delete restrict,
  valor_realizado numeric(15,2) not null default 0,
  origem         text not null default 'manual' check (origem in ('manual','excel','migracao_manus','bling')),
  criado_em      timestamptz not null default now(),
  atualizado_em  timestamptz not null default now(),
  atualizado_por text,
  unique (ano, mes, centro_custo_id)
);

-- ─── Provisão Prevista (antigo "mês 13" do Manus) — pode ser negativa ───────
create table public.cda_pa_provisao (
  id             bigint generated by default as identity primary key,
  ano            int not null check (ano between 2020 and 2100),
  centro_custo_id bigint not null references public.cda_pa_centro_custo(id) on delete restrict,
  valor_provisao numeric(15,2) not null default 0,
  criado_em      timestamptz not null default now(),
  atualizado_em  timestamptz not null default now(),
  atualizado_por text,
  unique (ano, centro_custo_id)
);

-- ─── Realizado anual legado (anos sem detalhe mensal, ex.: 2025) ────────────
create table public.cda_pa_realizado_anual_legado (
  id             bigint generated by default as identity primary key,
  ano            int not null check (ano between 2020 and 2100),
  centro_custo_id bigint not null references public.cda_pa_centro_custo(id) on delete restrict,
  valor_realizado numeric(15,2) not null default 0,
  criado_em      timestamptz not null default now(),
  atualizado_em  timestamptz not null default now(),
  atualizado_por text,
  unique (ano, centro_custo_id)
);

create index on public.cda_pa_subconta (conta_id);
create index on public.cda_pa_centro_custo (subconta_id);
create index on public.cda_pa_realizado_mensal (ano, mes);
create index on public.cda_pa_realizado_mensal (centro_custo_id);

-- ─── Triggers de carimbo ────────────────────────────────────────────────────
do $$
declare t text;
begin
  foreach t in array array['cda_pa_conta','cda_pa_subconta','cda_pa_centro_custo',
    'cda_pa_orcamento_previsto','cda_pa_realizado_mensal','cda_pa_provisao','cda_pa_realizado_anual_legado']
  loop
    execute format('create trigger touch before update on public.%I for each row execute function public.cda_pa_touch()', t);
  end loop;
end $$;

-- ─── RLS: leitura / inclusão / edição por permissão; exclusão só admin ──────
do $$
declare t text;
begin
  foreach t in array array['cda_pa_conta','cda_pa_subconta','cda_pa_centro_custo',
    'cda_pa_orcamento_previsto','cda_pa_realizado_mensal','cda_pa_provisao','cda_pa_realizado_anual_legado']
  loop
    execute format('alter table public.%I enable row level security', t);
    execute format('create policy leitura  on public.%I for select to authenticated using (public.cda_pa_pode_ler())', t);
    execute format('create policy inclusao on public.%I for insert to authenticated with check (public.cda_pa_pode_escrever())', t);
    execute format('create policy edicao   on public.%I for update to authenticated using (public.cda_pa_pode_escrever()) with check (public.cda_pa_pode_escrever())', t);
    execute format('create policy exclusao on public.%I for delete to authenticated using (public.cda_pa_is_admin())', t);
  end loop;
end $$;

-- ─── View base: hierarquia completa ─────────────────────────────────────────
create view public.cda_pa_v_hierarquia with (security_invoker = true) as
select c.id  as conta_id, c.nome as conta_nome, c.tipo, c.ordem as conta_ordem,
       s.id  as subconta_id, s.nome as subconta_nome, s.ordem as subconta_ordem,
       cc.id as centro_custo_id, cc.nome as centro_nome, cc.ordem as centro_ordem,
       (c.ativo and s.ativo and cc.ativo) as ativo
from public.cda_pa_centro_custo cc
join public.cda_pa_subconta s on s.id = cc.subconta_id
join public.cda_pa_conta    c on c.id = s.conta_id;

-- ─── View: Realizado anual por ano/centro (mensal 1–12 ou legado) ───────────
create view public.cda_pa_v_realizado_anual with (security_invoker = true) as
select coalesce(m.ano, l.ano) as ano,
       coalesce(m.centro_custo_id, l.centro_custo_id) as centro_custo_id,
       coalesce(m.total, l.valor_realizado, 0)::numeric(15,2) as valor_realizado,
       case when m.total is not null then 'mensal' else 'legado' end as fonte
from (select ano, centro_custo_id, sum(valor_realizado) total
        from public.cda_pa_realizado_mensal group by ano, centro_custo_id) m
full join public.cda_pa_realizado_anual_legado l
  on l.ano = m.ano and l.centro_custo_id = m.centro_custo_id;

-- ─── Função: último mês realizado (regra do Manus: 1º mês sem lançamento − 1)
create or replace function public.cda_pa_ultimo_mes_realizado(p_ano int) returns int
language sql stable security invoker set search_path = public as $$
  select coalesce(min(g.m) - 1, 12)::int
  from generate_series(1,12) g(m)
  where not exists (select 1 from cda_pa_realizado_mensal r where r.ano = p_ano and r.mes = g.m);
$$;

-- ─── View principal: Resumo anual por centro (base de todas as análises) ────
create view public.cda_pa_v_resumo_anual with (security_invoker = true) as
with anos as (
  select ano from public.cda_pa_orcamento_previsto
  union select ano from public.cda_pa_realizado_mensal
  union select ano from public.cda_pa_provisao
)
select a.ano, h.*,
       coalesce(p.valor_previsto, 0)::numeric(15,2)                       as previsto_anual,
       round(coalesce(p.valor_previsto, 0) / 12, 2)::numeric(15,2)         as previsto_mes,
       coalesce(ra.valor_realizado, 0)::numeric(15,2)                      as realizado_acumulado,
       coalesce(pv.valor_provisao, 0)::numeric(15,2)                       as provisao_prevista,
       coalesce(ant.valor_realizado, 0)::numeric(15,2)                     as realizado_ano_anterior,
       (coalesce(p.valor_previsto,0) - coalesce(ra.valor_realizado,0)
         - coalesce(pv.valor_provisao,0))::numeric(15,2)                   as saldo_total_a_realizar
from anos a
cross join public.cda_pa_v_hierarquia h
left join public.cda_pa_orcamento_previsto p  on p.ano  = a.ano and p.centro_custo_id  = h.centro_custo_id
left join public.cda_pa_v_realizado_anual  ra on ra.ano = a.ano and ra.centro_custo_id = h.centro_custo_id
left join public.cda_pa_provisao           pv on pv.ano = a.ano and pv.centro_custo_id = h.centro_custo_id
left join public.cda_pa_v_realizado_anual  ant on ant.ano = a.ano - 1 and ant.centro_custo_id = h.centro_custo_id;

grant select on public.cda_pa_v_hierarquia, public.cda_pa_v_realizado_anual, public.cda_pa_v_resumo_anual to authenticated;

notify pgrst, 'reload schema';
