-- Natureza da despesa: variável (acompanha a venda), fixa (estrutura) ou
-- financeira (bancos, juros, empréstimos). Subconta = padrão; centro de custo
-- pode ter exceção (null = herda da subconta). Receitas ficam null.
alter table public.cda_pa_subconta     add column if not exists natureza text;
alter table public.cda_pa_centro_custo add column if not exists natureza text;
do $$ begin
  alter table public.cda_pa_subconta add constraint cda_pa_subconta_natureza_chk
    check (natureza is null or natureza in ('variavel','fixa','financeira'));
exception when duplicate_object then null; end $$;
do $$ begin
  alter table public.cda_pa_centro_custo add constraint cda_pa_centro_custo_natureza_chk
    check (natureza is null or natureza in ('variavel','fixa','financeira'));
exception when duplicate_object then null; end $$;

-- Metas (% sobre a receita) por linha da Estrutura de Custos e por ano.
-- chave: 'sub:<id da subconta>' para fixas, 'financeira' para o grupo financeiro.
create table if not exists public.cda_pa_meta_estrutura (
  id            bigint generated by default as identity primary key,
  ano           integer not null,
  chave         text    not null,
  pct_mercado   numeric(6,2),
  pct_meta      numeric(6,2),
  atualizado_em timestamptz not null default now(),
  atualizado_por text,
  unique (ano, chave)
);
alter table public.cda_pa_meta_estrutura enable row level security;
do $$ begin
  create policy leitura  on public.cda_pa_meta_estrutura for select to authenticated using (public.cda_pa_pode_ler());
  create policy inclusao on public.cda_pa_meta_estrutura for insert to authenticated with check (public.cda_pa_pode_escrever());
  create policy edicao   on public.cda_pa_meta_estrutura for update to authenticated using (public.cda_pa_pode_escrever()) with check (public.cda_pa_pode_escrever());
  create policy exclusao on public.cda_pa_meta_estrutura for delete to authenticated using (public.cda_pa_is_admin());
exception when duplicate_object then null; end $$;

-- ─── Pré-classificação (revisável na Tabela Contábil) ──────────────────
update public.cda_pa_subconta s set natureza = case
    when s.nome in ('Produção Varejo','Produção Atacado','Montagem Coleções','Comerciais','Shows Grande Porte') then 'variavel'
    else 'fixa' end
  from public.cda_pa_conta c
 where c.id = s.conta_id and c.tipo = 'DESPESAS' and s.natureza is null;

-- Exceções por centro de custo
update public.cda_pa_centro_custo cc set natureza = 'financeira'
  from public.cda_pa_subconta s
 where s.id = cc.subconta_id and cc.natureza is null
   and ( (s.nome = 'Comerciais'      and cc.nome ilike 'Financeiras - Bancos%')
      or (s.nome = 'Administrativas' and cc.nome ilike 'Financeiras - Tarifas%') );
update public.cda_pa_centro_custo cc set natureza = 'variavel'
  from public.cda_pa_subconta s
 where s.id = cc.subconta_id and cc.natureza is null
   and s.nome = 'Marketing' and cc.nome ilike 'Market Place - Repasse%';

-- ─── Metas 2026 definidas pelo Cardoso (23/10/2026) ────────────────────
insert into public.cda_pa_meta_estrutura (ano, chave, pct_mercado, pct_meta, atualizado_por)
select 2026, 'sub:'||s.id, v.mercado, v.meta, 'migração 04'
  from public.cda_pa_subconta s
  join (values ('Pessoal',18.0,15.0),('Administrativas',10.0,10.0),('Marketing',7.5,7.5)) v(nome,mercado,meta) on v.nome = s.nome
on conflict (ano, chave) do nothing;
insert into public.cda_pa_meta_estrutura (ano, chave, pct_mercado, pct_meta, atualizado_por)
values (2026, 'financeira', 5.0, 5.0, 'migração 04')
on conflict (ano, chave) do nothing;
