-- Eventos realizados lançados pela Prestação de Contas — 01/11/2026 (Cardoso).
-- • canais.exige_eventos: o canal precisa registrar eventos do mês (nº, locais, público) na prestação.
--   Ligado nos canais dos grupos Shows de artistas (15) e Feiras e bazares (19).
-- • cda_canal_eventos_mes: concluido / concluido_por / concluido_em. Os 54 meses carregados da planilha
--   de 30/10/2026 ficam concluídos (sem público; a obrigatoriedade do público vale daqui em diante).
-- • cda_canal_eventos_mes_log: histórico de conclusões e correções (antes/depois, motivo, usuário).
-- Regra (na tela): prestação só sai de "Em Aberto" com os eventos de todos os canais marcados concluídos;
-- prestação Enviada/Finalizada: correção pelo botão "Corrigir" com motivo obrigatório (fica no log).
-- ════════════════════════════════════════════════════════════════════
alter table public.canais add column if not exists exige_eventos boolean not null default false;
update public.canais set exige_eventos = true where grupo_id in (15, 19) and not exige_eventos;

alter table public.cda_canal_eventos_mes add column if not exists concluido boolean not null default false;
alter table public.cda_canal_eventos_mes add column if not exists concluido_por text;
alter table public.cda_canal_eventos_mes add column if not exists concluido_em timestamptz;
update public.cda_canal_eventos_mes set concluido = true, concluido_por = 'Planilha Cardoso 30/10/2026', concluido_em = now()
 where not concluido; -- todos os meses já registrados até 01/11/2026 (54, da planilha)

create table if not exists public.cda_canal_eventos_mes_log (
  id          bigint generated by default as identity primary key,
  canal_id    bigint not null references public.canais(id) on delete cascade,
  ano_mes     text not null,
  acao        text not null check (acao in ('conclusao','correcao')),
  antes       jsonb,
  depois      jsonb,
  motivo      text,
  prestacao_id bigint,
  usuario     text,
  criado_em   timestamptz not null default now()
);
alter table public.cda_canal_eventos_mes_log enable row level security;
drop policy if exists membros_equipe on public.cda_canal_eventos_mes_log;
create policy membros_equipe on public.cda_canal_eventos_mes_log for all to authenticated
  using (public.cda_e_membro_equipe()) with check (public.cda_e_membro_equipe());
