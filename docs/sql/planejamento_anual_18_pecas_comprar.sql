-- ════════════════════════════════════════════════════════════════════
-- Planejamento Anual — Tabela de Peças a Comprar (02/11/2026, Cardoso).
-- Tela Análises e Decisões › Compras de Produção › Saldo de Compras Anual (Peças).
-- Cada linha: mês da compra, grupo de receita (obrigatório; o segmento Varejo/Atacado vem do grupo),
-- centro de receita (opcional — vazio = "Geral do grupo"; nenhum centro novo é criado no Plano de Contas),
-- peça (texto livre; no futuro, ligada ao cadastro de produtos), quantidade, valor unitário e status.
-- Status: 'planejada' (entra no confronto com o Saldo de Compras) | 'encomendada' (já está nas Provisões,
-- fica fora do confronto para não contar duas vezes).
-- Sem dados antigos.
-- ════════════════════════════════════════════════════════════════════
create table if not exists public.cda_pa_pecas_compra (
  id              bigint generated by default as identity primary key,
  ano             int  not null check (ano between 2020 and 2100),
  mes             int  not null check (mes between 1 and 12),
  grupo_id        bigint not null references public.cda_grupo(id),
  centro_custo_id bigint references public.cda_pa_centro_custo(id),
  peca            text not null check (length(trim(peca)) > 0),
  quantidade      numeric(12,2) not null default 0 check (quantidade >= 0),
  valor_unitario  numeric(12,2) not null default 0 check (valor_unitario >= 0),
  status          text not null default 'planejada' check (status in ('planejada','encomendada')),
  observacao      text,
  criado_por      text,
  criado_em       timestamptz not null default now(),
  atualizado_por  text,
  atualizado_em   timestamptz not null default now()
);
create index if not exists cda_pa_pecas_compra_ano_idx on public.cda_pa_pecas_compra (ano, mes);
alter table public.cda_pa_pecas_compra enable row level security;
drop policy if exists leitura  on public.cda_pa_pecas_compra;
drop policy if exists inclusao on public.cda_pa_pecas_compra;
drop policy if exists edicao   on public.cda_pa_pecas_compra;
drop policy if exists exclusao on public.cda_pa_pecas_compra;
create policy leitura  on public.cda_pa_pecas_compra for select to authenticated using (public.cda_pa_pode_ler());
create policy inclusao on public.cda_pa_pecas_compra for insert to authenticated with check (public.cda_pa_pode_escrever());
create policy edicao   on public.cda_pa_pecas_compra for update to authenticated using (public.cda_pa_pode_escrever()) with check (public.cda_pa_pode_escrever());
create policy exclusao on public.cda_pa_pecas_compra for delete to authenticated using (public.cda_pa_pode_escrever());
