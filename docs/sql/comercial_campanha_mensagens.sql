-- Comercial · Biblioteca de Mensagens de E-mail (06/11/2026)
-- Cada mensagem pertence a uma campanha (uma campanha pode ter várias).
-- Só acréscimos: tabela nova, submódulo de permissão novo e cópia do
-- e-mail que estava em cda_campanhas.email_* (colunas antigas mantidas).
-- ════════════════════════════════════════════════════════════════════

create table if not exists public.cda_campanha_mensagens (
  id               bigint generated by default as identity primary key,
  campanha_id      bigint references public.cda_campanhas(id) on delete set null,
  nome             text not null,
  remetente_nome   text,
  remetente_email  text,
  responder_para   text,
  assunto          text,
  previa           text,
  conteudo         jsonb not null default '{}'::jsonb,
  ultimo_teste_em  timestamptz,
  ultimo_teste_para text,
  criado_em        timestamptz not null default now(),
  criado_por       text,
  atualizado_em    timestamptz not null default now(),
  atualizado_por   text
);
create index if not exists cda_campanha_mensagens_campanha_idx on public.cda_campanha_mensagens(campanha_id);
comment on table public.cda_campanha_mensagens is
  'Biblioteca de mensagens de e-mail das campanhas. conteudo = blocos (imagemUrl, imagemAlt, titulo, saudacao, texto, cupomCodigo, cupomTexto, botaoTexto, botaoLink, infoTitulo, infoTexto, sacTitulo, sacTelefone, sacEmail, rodape). Montado por cdaMontarEmailCampanha().';

alter table public.cda_campanha_mensagens enable row level security;
drop policy if exists membros_equipe on public.cda_campanha_mensagens;
create policy membros_equipe on public.cda_campanha_mensagens for all to authenticated
  using (public.cda_e_membro_equipe()) with check (public.cda_e_membro_equipe());

-- Submódulo de permissão (mesmo nível que cada pessoa já tem em Campanhas)
insert into public.cda_permissoes_catalogo (projeto, submodulo_slug, submodulo_label, ordem)
select 'comercial', 'mensagens', 'Biblioteca de Mensagens', 5
where not exists (select 1 from public.cda_permissoes_catalogo where projeto = 'comercial' and submodulo_slug = 'mensagens');

insert into public.cda_equipe_permissoes (equipe_id, submodulo_id, nivel)
select p.equipe_id, novo.id, p.nivel
from public.cda_equipe_permissoes p
join public.cda_permissoes_catalogo camp on camp.id = p.submodulo_id and camp.projeto = 'comercial' and camp.submodulo_slug = 'campanhas'
cross join (select id from public.cda_permissoes_catalogo where projeto = 'comercial' and submodulo_slug = 'mensagens') novo
where not exists (select 1 from public.cda_equipe_permissoes x where x.equipe_id = p.equipe_id and x.submodulo_id = novo.id);

