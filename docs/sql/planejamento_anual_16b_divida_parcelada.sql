-- ════════════════════════════════════════════════════════════════════
-- Planejamento Anual — cadastro de dívidas parceladas (tributos renegociados) — 31/10/2026 (Cardoso).
-- Os tributos de 2026 (mar–out) foram renegociados em parcelamento de 60 meses: deixam de ser provisão de 2026
-- (Cardoso zerou a provisão de "Impostos sobre vendas", R$ 77.811,96) e passam a dívida de longo prazo. As parcelas
-- entram no Realizado/Previsto do centro "Impostos - Parcelamento" mês a mês. Este cadastro guarda a dívida e
-- alimenta o aviso informativo da Visão Anual ("fora do resultado de caixa") e, depois, o orçamento de 2027+.
-- Dados do parcelamento (valor negociado, nº e valor das parcelas, 1º vencimento) pendentes de Cardoso.
-- ════════════════════════════════════════════════════════════════════
create table if not exists public.cda_pa_divida_parcelada (
  id               bigint generated by default as identity primary key,
  descricao        text not null,
  ano_competencia  int not null,
  valor_original   numeric not null,
  valor_negociado  numeric,
  n_parcelas       int,
  valor_parcela    numeric,
  primeiro_venc    date,
  centro_custo_id  bigint references public.cda_pa_centro_custo(id),
  observacao       text,
  atualizado_por   text,
  atualizado_em    timestamptz not null default now()
);
alter table public.cda_pa_divida_parcelada enable row level security;
drop policy if exists leitura on public.cda_pa_divida_parcelada;
drop policy if exists gravacao on public.cda_pa_divida_parcelada;
create policy leitura on public.cda_pa_divida_parcelada for select to authenticated using (public.cda_pa_pode_ler());
create policy gravacao on public.cda_pa_divida_parcelada for all to authenticated using (public.cda_pa_pode_escrever()) with check (public.cda_pa_pode_escrever());

insert into public.cda_pa_divida_parcelada (descricao, ano_competencia, valor_original, n_parcelas, centro_custo_id, observacao, atualizado_por)
select 'Tributos 2026 (mar–out) — novo parcelamento', 2026, 77811.96, 60,
       (select id from public.cda_pa_centro_custo where nome ilike 'Impostos - Parcelamento%' limit 1),
       'Valor da provisão de Impostos sobre vendas zerada em 31/10/2026. Valor negociado, parcela e 1º vencimento a informar.',
       'Cardoso 31/10/2026'
where not exists (select 1 from public.cda_pa_divida_parcelada where descricao = 'Tributos 2026 (mar–out) — novo parcelamento');
