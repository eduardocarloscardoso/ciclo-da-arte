create table if not exists public.cda_canal_eventos_mes (
  id           bigint generated by default as identity primary key,
  canal_id     bigint not null references public.canais(id) on delete cascade,
  ano_mes      text not null check (ano_mes ~ '^\d{4}-(0[1-9]|1[0-2])$'),
  qtd_eventos  int not null check (qtd_eventos >= 0),
  observacao   text,
  origem       text not null default 'manual',
  atualizado_por text,
  atualizado_em  timestamptz not null default now(),
  unique (canal_id, ano_mes)
);
alter table public.cda_canal_eventos_mes enable row level security;
drop policy if exists membros_equipe on public.cda_canal_eventos_mes;
create policy membros_equipe on public.cda_canal_eventos_mes for all to authenticated
  using (public.cda_e_membro_equipe()) with check (public.cda_e_membro_equipe());

