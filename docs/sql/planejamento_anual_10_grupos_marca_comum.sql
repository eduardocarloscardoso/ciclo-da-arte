-- Natureza do centro (própria ou herdada da subconta) = natureza do grupo
create or replace function public.cda_pa_valida_grupo_centro() returns trigger
language plpgsql security definer set search_path to 'public' as $$
declare g record; nat text;
begin
  if new.grupo_id is null then return new; end if;
  select * into g from public.cda_grupo where id = new.grupo_id;
  if g.tipo <> 'Despesa' then raise exception 'Centro de custo só pode ser ligado a grupo de Despesa.' using errcode='23514'; end if;
  select coalesce(new.natureza, s.natureza) into nat from public.cda_pa_subconta s where s.id = new.subconta_id;
  if g.natureza is not null and nat is distinct from g.natureza then
    raise exception 'Natureza do centro (%) diferente da natureza do grupo "%" (%).', coalesce(nat,'—'), g.nome, g.natureza using errcode='23514';
  end if;
  return new;
end $$;
drop trigger if exists cda_pa_valida_grupo_centro on public.cda_pa_centro_custo;
create trigger cda_pa_valida_grupo_centro before insert or update of grupo_id, natureza, subconta_id on public.cda_pa_centro_custo
  for each row execute function public.cda_pa_valida_grupo_centro();

-- Trava: Mercado % e Marca comum só o administrador altera
create or replace function public.cda_pa_trava_mercado() returns trigger
language plpgsql security definer set search_path to 'public' as $$
begin
  if auth.jwt() ->> 'email' is null then return new; end if;
  if (tg_op = 'INSERT' and (new.pct_mercado is not null or new.pct_marca_comum is not null))
     or (tg_op = 'UPDATE' and (new.pct_mercado is distinct from old.pct_mercado or new.pct_marca_comum is distinct from old.pct_marca_comum)) then
    if not public.cda_pa_is_admin() then
      raise exception 'Somente o administrador pode alterar o Mercado %% e a Marca comum.' using errcode = '42501';
    end if;
  end if;
  return new;
end $$;

