-- Planejamento Anual › 🧪 Simulações › Simulação de Compras por Campanha — 31/10/2026 (Cardoso).
-- • cda_pa_sim_cenario: cenários salvos de uma campanha do Calendário Comercial. Guarda só as metas
--   de receita digitadas por grupo (metas jsonb: {"grupos": {"<grupo_id>": valor, ...}}); as compras,
--   provisões e saldos são sempre recalculados com os dados do dia.
-- ════════════════════════════════════════════════════════════════════
create table if not exists public.cda_pa_sim_cenario (
  id            bigint generated by default as identity primary key,
  campanha_id   bigint not null references public.cda_cal_campanha(id) on delete cascade,
  nome          text not null,
  metas         jsonb not null default '{}'::jsonb,
  observacoes   text,
  criado_por    text,
  criado_em     timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  unique (campanha_id, nome)
);
alter table public.cda_pa_sim_cenario enable row level security;
drop policy if exists leitura on public.cda_pa_sim_cenario;
drop policy if exists gravacao on public.cda_pa_sim_cenario;
create policy leitura on public.cda_pa_sim_cenario for select to authenticated using (public.cda_pa_pode_ler());
create policy gravacao on public.cda_pa_sim_cenario for all to authenticated
  using (public.cda_pa_pode_escrever()) with check (public.cda_pa_pode_escrever());

create or replace function public.cda_pa_sim_cenario_touch() returns trigger
language plpgsql set search_path to 'public' as $$
begin new.atualizado_em := now(); return new; end $$;
drop trigger if exists cda_pa_sim_cenario_touch on public.cda_pa_sim_cenario;
create trigger cda_pa_sim_cenario_touch before update on public.cda_pa_sim_cenario
  for each row execute function public.cda_pa_sim_cenario_touch();
