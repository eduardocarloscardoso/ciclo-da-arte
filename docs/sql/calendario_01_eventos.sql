-- Ecossistema — Calendário Comercial (fatia 1) — 30/10/2026 (Cardoso).
-- • Tabela de eventos/ações do calendário comercial (projeto "Calendário" da barra lateral).
--   Cada evento se liga a um centro de RECEITA (canal no Planejamento — ex.: SHOWS LUEDJI LUNA,
--   REVENDA FUTURA 1) ou a um GRUPO de receita (ex.: E-commerce = todos os canais de e-commerce).
--   Critério: Unidades | Pedidos | A definir. Projeção (fatia 2) e realizado (fatia 4) ficam em branco.
-- • Novo centro de receita "E-COMMERCE IZA" (subconta E-COMMERCE, grupo E-commerce) e novo canal do
--   Financeiro "E-COMMERCE IZA": comissão 15% (centro Comissões Artistas Collabs), imposto padrão.
-- ════════════════════════════════════════════════════════════════════
create table if not exists public.cda_cal_evento (
  id               bigint generated by default as identity primary key,
  ano              int not null,
  mes              int check (mes between 1 and 12),
  inicio           date,
  fim              date,
  evento           text not null,
  collab           text,
  centro_custo_id  bigint references public.cda_pa_centro_custo(id),
  grupo_id         bigint references public.cda_grupo(id),
  criterio         text not null default 'A definir' check (criterio in ('Unidades','Pedidos','A definir')),
  status           text not null default 'Planejado' check (status in ('Planejado','A confirmar','A definir','Confirmado','Realizado','Cancelado')),
  acao_ia          text,
  local            text,
  observacoes      text,
  qtd_prevista     numeric,
  ticket_medio     numeric,
  projecao         numeric,
  realizado        numeric,
  origem           text not null default 'manual' check (origem in ('manual','excel')),
  criado_por       text,
  criado_em        timestamptz not null default now(),
  atualizado_em    timestamptz not null default now(),
  check (fim is null or inicio is null or fim >= inicio)
);
create index if not exists cda_cal_evento_ano_mes on public.cda_cal_evento (ano, mes);

alter table public.cda_cal_evento enable row level security;
drop policy if exists membros_equipe on public.cda_cal_evento;
create policy membros_equipe on public.cda_cal_evento for all to authenticated
  using (public.cda_e_membro_equipe()) with check (public.cda_e_membro_equipe());

create or replace function public.cda_cal_evento_touch() returns trigger
language plpgsql set search_path to 'public' as $$
begin
  new.atualizado_em := now();
  if new.inicio is not null then new.ano := extract(year from new.inicio); new.mes := extract(month from new.inicio); end if;
  return new;
end $$;
drop trigger if exists cda_cal_evento_touch on public.cda_cal_evento;
create trigger cda_cal_evento_touch before insert or update on public.cda_cal_evento
  for each row execute function public.cda_cal_evento_touch();

-- Centro de receita E-COMMERCE IZA (subconta E-COMMERCE = 3, grupo E-commerce = 22)
insert into public.cda_pa_centro_custo (nome, subconta_id, ordem, grupo_id)
select 'E-COMMERCE IZA', 3, coalesce((select max(ordem) from public.cda_pa_centro_custo where subconta_id = 3), 0) + 1, 22
where not exists (select 1 from public.cda_pa_centro_custo where nome = 'E-COMMERCE IZA');

-- Canal do Financeiro E-COMMERCE IZA (comissão 15% → Comissões Artistas Collabs 60001; imposto padrão = vazio)
insert into public.canais (id, nome, tipo, comissao, escopo, grupo_id, centro_custo_id, comissao_centro_id)
select (extract(epoch from clock_timestamp()) * 1000)::bigint, 'E-COMMERCE IZA', 'artista', 15, 'b2c', 22,
       (select id from public.cda_pa_centro_custo where nome = 'E-COMMERCE IZA'), 60001
where not exists (select 1 from public.canais where nome = 'E-COMMERCE IZA');
