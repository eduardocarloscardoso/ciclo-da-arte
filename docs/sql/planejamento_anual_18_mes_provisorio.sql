-- ════════════════════════════════════════════════════════════════════
-- Planejamento Anual — mês provisório (02/11/2026, Cardoso).
-- Marca o Realizado de um mês/conta como PROVISÓRIO (planilha temporária, mês ainda não fechado).
-- As telas de acompanhamento e análise mostram a etiqueta "mês/ano provisório" enquanto a marca existir.
-- A importação do Realizado tem a opção "Importação provisória": marcada grava a marca; desmarcada
-- (importação definitiva) apaga a marca daquele mês e conta. Também dá para marcar/desmarcar na aba Realizado.
-- Carga inicial: receitas de outubro/2026 (planilha temporária importada em 31/10/2026).
-- Não altera nenhum valor realizado.
-- ════════════════════════════════════════════════════════════════════
create table if not exists public.cda_pa_mes_provisorio (
  id          bigint generated by default as identity primary key,
  ano         int  not null check (ano between 2020 and 2100),
  mes         int  not null check (mes between 1 and 12),
  tipo        text not null check (tipo in ('RECEITAS','DESPESAS')),
  observacao  text,
  marcado_por text,
  marcado_em  timestamptz not null default now(),
  unique (ano, mes, tipo)
);
alter table public.cda_pa_mes_provisorio enable row level security;
drop policy if exists leitura on public.cda_pa_mes_provisorio;
drop policy if exists inclusao on public.cda_pa_mes_provisorio;
drop policy if exists edicao on public.cda_pa_mes_provisorio;
drop policy if exists exclusao on public.cda_pa_mes_provisorio;
create policy leitura  on public.cda_pa_mes_provisorio for select to authenticated using (public.cda_pa_pode_ler());
create policy inclusao on public.cda_pa_mes_provisorio for insert to authenticated with check (public.cda_pa_pode_escrever());
create policy edicao   on public.cda_pa_mes_provisorio for update to authenticated using (public.cda_pa_pode_escrever()) with check (public.cda_pa_pode_escrever());
create policy exclusao on public.cda_pa_mes_provisorio for delete to authenticated using (public.cda_pa_pode_escrever());

insert into public.cda_pa_mes_provisorio (ano, mes, tipo, observacao, marcado_por, marcado_em)
values (2026, 10, 'RECEITAS', 'Planilha temporária de receitas de outubro importada em 31/10/2026 — aguardando o fechamento definitivo', 'Cardoso', '2026-10-31 12:00:00-03')
on conflict (ano, mes, tipo) do nothing;
