create table if not exists public.cda_pa_plano_acao (
  id              bigint generated by default as identity primary key,
  ano             integer not null,
  centro_custo_id bigint  not null references public.cda_pa_centro_custo(id),
  texto           text    not null check (length(trim(texto)) > 0),
  criado_por      text,
  criado_em       timestamptz not null default now()
);
create index if not exists cda_pa_plano_acao_cc on public.cda_pa_plano_acao (centro_custo_id, ano, criado_em desc);
alter table public.cda_pa_plano_acao enable row level security;
do $$ begin
  create policy leitura  on public.cda_pa_plano_acao for select to authenticated using (public.cda_pa_pode_ler());
  create policy inclusao on public.cda_pa_plano_acao for insert to authenticated with check (public.cda_pa_pode_escrever());
  create policy exclusao on public.cda_pa_plano_acao for delete to authenticated using (public.cda_pa_is_admin());
exception when duplicate_object then null; end $$;
