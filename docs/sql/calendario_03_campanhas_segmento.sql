-- ════════════════════════════════════════════════════════════════════
-- Calendário Comercial — Campanhas e Segmento Varejo/Atacado — 31/10/2026 (aprovado por Cardoso).
-- • cda_grupo.segmento ('varejo' | 'atacado'): só grupos de RECEITA. Regra: tudo é Varejo, menos
--   "Atacado / Private Label". O evento herda o segmento do grupo (direto ou pelo grupo do centro).
-- • cda_cal_campanha: nível macro que agrupa eventos de um período (ex.: Black Friday / Natal 2026).
--   cda_cal_evento.campanha_id liga o evento à campanha (opcional).
-- • Carga: campanha "Black Friday / Natal 2026" (01/11–31/12/2026) com os 24 eventos de nov/dez 2026.
-- ════════════════════════════════════════════════════════════════════
alter table public.cda_grupo add column if not exists segmento text
  check (segmento is null or segmento in ('varejo','atacado'));
update public.cda_grupo set segmento = case when id = 14 then 'atacado' else 'varejo' end
 where tipo = 'Receita' and segmento is null;

create table if not exists public.cda_cal_campanha (
  id            bigint generated by default as identity primary key,
  nome          text not null unique,
  inicio        date not null,
  fim           date not null,
  objetivo      text,
  status        text not null default 'Planejada' check (status in ('Planejada','Em andamento','Encerrada','Cancelada')),
  observacoes   text,
  criado_por    text,
  criado_em     timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  check (fim >= inicio)
);
alter table public.cda_cal_campanha enable row level security;
drop policy if exists membros_equipe on public.cda_cal_campanha;
create policy membros_equipe on public.cda_cal_campanha for all to authenticated
  using (public.cda_e_membro_equipe()) with check (public.cda_e_membro_equipe());

create or replace function public.cda_cal_campanha_touch() returns trigger
language plpgsql set search_path to 'public' as $$
begin new.atualizado_em := now(); return new; end $$;
drop trigger if exists cda_cal_campanha_touch on public.cda_cal_campanha;
create trigger cda_cal_campanha_touch before update on public.cda_cal_campanha
  for each row execute function public.cda_cal_campanha_touch();

alter table public.cda_cal_evento add column if not exists campanha_id bigint
  references public.cda_cal_campanha(id) on delete set null;
create index if not exists cda_cal_evento_campanha on public.cda_cal_evento (campanha_id);

insert into public.cda_cal_campanha (nome, inicio, fim, objetivo, status, criado_por)
values ('Black Friday / Natal 2026', '2026-11-01', '2026-12-31',
        'Vendas de fim de ano: Black Friday, Cyber Monday e Natal, com shows, feiras, lançamentos e private label de nov–dez 2026',
        'Planejada', 'Cardoso 31/10/2026')
on conflict (nome) do nothing;

update public.cda_cal_evento e set campanha_id = c.id
  from public.cda_cal_campanha c
 where c.nome = 'Black Friday / Natal 2026' and e.ano = 2026 and e.mes in (11, 12) and e.campanha_id is null;
